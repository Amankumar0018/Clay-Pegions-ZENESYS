class NetSuiteIntegrationService:
    """
    NetSuite Enterprise Integration Service
    Architecture: FastAPI Backend -> NetSuite SuiteTalk REST / RESTlet (OAuth 2.0 / TBA)
    Supports both Live NetSuite REST API and a robust Demo/Sandbox mode.
    """

    def __init__(self):
        self.account_id = os.getenv("NETSUITE_ACCOUNT_ID", "TSTDRV1234567")
        self.client_id = os.getenv("NETSUITE_CLIENT_ID", "")
        self.client_secret = os.getenv("NETSUITE_CLIENT_SECRET", "")
        self.token_id = os.getenv("NETSUITE_TOKEN_ID", "")
        self.token_secret = os.getenv("NETSUITE_TOKEN_SECRET", "")
        self.base_url = os.getenv("NETSUITE_BASE_URL", f"https://{self.account_id.lower().replace('_', '-')}.suitetalk.api.netsuite.com/services/rest/record/v1")
        self.mode = os.getenv("NETSUITE_MODE", "demo").lower() # 'live' or 'demo'

    def get_status(self) -> Dict[str, Any]:
        """Returns NetSuite connection status and sync telemetry."""
        is_live = self.mode == "live" and bool(self.client_id and self.client_secret)
        return {
            "status": "Connected" if (is_live or self.mode == "demo") else "Disconnected",
            "mode": "Live NetSuite REST API" if is_live else "Demo / Sandbox Mode",
            "is_demo_mode": not is_live,
            "account_id": self.account_id,
            "api_version": "v1 (SuiteTalk REST)",
            "auth_type": "OAuth 2.0 / TBA",
            "last_sync": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "sync_health": "Healthy",
            "records_synced": {
                "items": 20,
                "vendors": 60,
                "purchase_orders": 14,
                "inventory_snapshots": 20
            }
        }

